import { HEAVY_DIRS, type RepoContext } from '../context.js';
import type { Check, CheckResult, FileChange, Finding } from '../types.js';
import { isExamplePath, isFixturePath, isTestPath } from '../util/paths.js';

export const SOURCE_EXT =
  /\.(?:[cm]?[jt]sx?|py|pyi|vue|svelte|astro|css|scss|less|html?|go|rs|java|kt|rb|php|cs|swift|c|cc|cpp|h|hpp)$/;
const LOCKFILES = [
  'package-lock.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lockb',
  'bun.lock',
  'npm-shrinkwrap.json',
];
const PY_LOCKS = ['poetry.lock', 'uv.lock', 'Pipfile.lock', 'pdm.lock'];

const LARGE_LINES = 1000;
const HUGE_BYTES = 1024 * 1024;

/** Third-party code copied into the repo (jquery-1.12.4.js, vendor/, third_party/). */
export function isVendored(f: string): boolean {
  return (
    /(^|\/)(vendor|vendors|third[-_]party|thirdparty|external|bower_components)\//i.test(f) ||
    /[-.]v?\d+\.\d+(\.\d+)?([-.]\w+)?(\.min)?\.(js|css)$/.test(f)
  );
}

export function isGeneratedName(f: string): boolean {
  return (
    /\.min\.(js|css|mjs)$/.test(f) ||
    /\.(js|css)\.map$/.test(f) ||
    /(^|[./_-])(bundle|chunk|vendor)[.-][\w.-]*\.js$/.test(f) ||
    /[._-]generated\.\w+$/.test(f) ||
    /(^|\/)(generated|zz_generated[\w.]*)\.\w+$/.test(f) ||
    /\.gen\.\w+$/.test(f) ||
    /(^|\/)(generated|__generated__)\//.test(f) ||
    /_pb2(_grpc)?\.pyi?$/.test(f) ||
    /\.pb\.(go|ts|js)$/.test(f) ||
    /\.snap$/.test(f) ||
    LOCKFILES.some((l) => f === l || f.endsWith(`/${l}`)) ||
    PY_LOCKS.some((l) => f === l || f.endsWith(`/${l}`))
  );
}

const GENERATED_HEADER =
  /@generated|DO NOT EDIT|do not modify|auto-?generated|generated by|generated (?:file|code)|code generated/i;

interface IgnoreCandidate {
  entry: string;
  /** Directory name to look for on disk / in visible paths. */
  dir?: string;
  /** Visible-file regex. */
  file?: RegExp;
  /** Only flag dirs that contain no tracked files (could be source otherwise). */
  onlyIfUntracked?: boolean;
  lang?: 'js' | 'py';
}

const CANDIDATES: IgnoreCandidate[] = [
  ...HEAVY_DIRS.map((d) => ({ entry: `${d}/`, dir: d })),
  { entry: 'dist/', dir: 'dist', onlyIfUntracked: true },
  { entry: 'build/', dir: 'build', onlyIfUntracked: true },
  { entry: 'out/', dir: 'out', onlyIfUntracked: true },
  // Maven and Cargo build output.
  { entry: 'target/', dir: 'target', onlyIfUntracked: true },
  { entry: 'coverage/', dir: 'coverage', onlyIfUntracked: true },
  { entry: '.cache/', dir: '.cache', onlyIfUntracked: true },
  { entry: '*.egg-info/', file: /(^|\/)[^/]+\.egg-info\// },
  { entry: '*.pyc', file: /\.py[co]$/ },
  { entry: '.DS_Store', file: /(^|\/)\.DS_Store$/ },
  { entry: '*.log', file: /(^|\/)(npm-debug|yarn-error|yarn-debug)\.log/ },
  { entry: '.env', file: /(^|\/)\.env$/ },
];

/** Entries that should be added to .gitignore. */
export function missingIgnoreEntries(ctx: RepoContext): Array<{ entry: string; reason: string }> {
  const out: Array<{ entry: string; reason: string }> = [];
  for (const c of CANDIDATES) {
    if (c.dir) {
      if (!ctx.exists(c.dir)) continue;
      if (ctx.isIgnored(c.dir)) continue;
      if (c.onlyIfUntracked && (!ctx.isGit || ctx.hasTracked(c.dir))) continue;
      out.push({ entry: c.entry, reason: `\`${c.dir}/\` exists and is not ignored` });
    } else if (c.file) {
      const re = c.file;
      // A .env under examples/ or test fixtures is a template, not a leaked local config.
      const hit = ctx.files.find(
        (f) => re.test(f) && !(c.entry === '.env' && (isExamplePath(f) || isTestPath(f))),
      );
      if (hit) out.push({ entry: c.entry, reason: `\`${hit}\` is visible to agents` });
    }
  }
  return out;
}

const BASE_GITIGNORE: Record<string, string[]> = {
  js: ['node_modules/', 'dist/', 'coverage/', '*.log', '.env', '.env.*', '!.env.example'],
  py: [
    '__pycache__/',
    '*.py[cod]',
    '.venv/',
    'venv/',
    '*.egg-info/',
    '.pytest_cache/',
    '.mypy_cache/',
    '.ruff_cache/',
    '.env',
  ],
  common: ['.DS_Store'],
};

function gitignoreFix(ctx: RepoContext): FileChange[] {
  const before = ctx.read('.gitignore');
  if (before === null) {
    const entries = [
      ...(ctx.pkg ? (BASE_GITIGNORE.js ?? []) : []),
      ...(ctx.languages.includes('python') ? (BASE_GITIGNORE.py ?? []) : []),
      ...(BASE_GITIGNORE.common ?? []),
    ];
    const unique = [...new Set(entries)];
    return [
      {
        path: '.gitignore',
        before: null,
        after: `# Generated by agent-ready\n${unique.join('\n')}\n`,
        kind: 'create',
        description: 'Create .gitignore so dependency/build dirs stay out of agent context',
      },
    ];
  }
  const missing = missingIgnoreEntries(ctx).map((m) => m.entry);
  const existing = new Set(before.split(/\r?\n/).map((l) => l.trim()));
  const toAdd = [...new Set(missing)].filter(
    (e) => !existing.has(e) && !existing.has(e.replace(/\/$/, '')),
  );
  if (toAdd.length === 0) return [];
  const sep = before.endsWith('\n') || before === '' ? '' : '\n';
  return [
    {
      path: '.gitignore',
      before,
      after: `${before}${sep}\n# Added by agent-ready\n${toAdd.join('\n')}\n`,
      kind: 'append',
      description: `Add ${toAdd.length} ignore entr${toAdd.length === 1 ? 'y' : 'ies'}`,
    },
  ];
}

const VENV_DIRS = new Set(['.venv', 'venv']);

/**
 * Committed dependency/cache files that are actually a mistake. Test fixtures often commit a fake
 * `node_modules/` on purpose, and `venv/` can be a real source package (e.g. stubs for the stdlib
 * `venv` module), so it only counts when it looks like an actual virtualenv.
 */
function committedHeavy(ctx: RepoContext): string[] {
  const realVenvs = new Set<string>();
  for (const f of ctx.trackedHeavy) {
    const m =
      /^(.*?(?:^|\/)\.?venv)\/(?:pyvenv\.cfg$|bin\/activate|lib\/python[\d.]+\/site-packages\/)/.exec(
        f,
      );
    if (m?.[1]) realVenvs.add(m[1]);
  }
  return ctx.trackedHeavy.filter((f) => {
    if (isTestPath(f) || isExamplePath(f)) return false;
    const parts = f.split('/');
    const i = parts.findIndex((p) => (HEAVY_DIRS as readonly string[]).includes(p));
    const seg = parts[i] ?? '';
    if (!VENV_DIRS.has(seg)) return true;
    return realVenvs.has(parts.slice(0, i + 1).join('/'));
  });
}

export const navigabilityChecks: Check[] = [
  {
    id: 'nav.gitignore',
    category: 'navigability',
    title: 'Build/dependency output is ignored',
    weight: 3,
    run(ctx): CheckResult {
      const findings: Finding[] = [];
      if (!ctx.exists('.gitignore')) {
        findings.push({
          severity: 'error',
          message: 'No .gitignore — agents will search build output and dependencies',
        });
      }
      const heavy = committedHeavy(ctx);
      if (heavy.length) {
        const dirs = [
          ...new Set(
            heavy.map((f) =>
              f.split('/').find((s) => (HEAVY_DIRS as readonly string[]).includes(s)),
            ),
          ),
        ];
        findings.push({
          severity: 'error',
          message: `${heavy.length} file(s) committed inside ${dirs.join(', ')} — run \`git rm -r --cached ${dirs.join(' ')}\``,
        });
      }
      for (const m of missingIgnoreEntries(ctx)) {
        findings.push({
          severity: 'warn',
          message: `${m.reason}; add \`${m.entry}\` to .gitignore`,
        });
      }
      const penalty = findings.reduce((s, f) => s + (f.severity === 'error' ? 0.5 : 0.2), 0);
      const score = Math.max(0, 1 - penalty);
      return {
        score,
        summary:
          findings.length === 0
            ? 'Dependency and build output are ignored'
            : `${findings.length} ignore problem(s)`,
        findings,
        suggestion: findings.length
          ? 'Run `agent-ready --fix` to add the missing .gitignore entries.'
          : undefined,
      };
    },
    fix: gitignoreFix,
  },
  {
    id: 'nav.large-files',
    category: 'navigability',
    title: `No oversized source files (>${LARGE_LINES} lines)`,
    weight: 3,
    async run(ctx): Promise<CheckResult> {
      // Test fixtures and snapshot baselines are data: nobody splits them, agents rarely read them whole.
      // Declaration files (`lib.dom.d.ts`) are generated or bundled, not something to split.
      const sources = ctx.files.filter(
        (f) =>
          SOURCE_EXT.test(f) &&
          !f.endsWith('.d.ts') &&
          !isGeneratedName(f) &&
          !isVendored(f) &&
          !isFixturePath(f),
      );
      // Too small to exceed the limit, or huge (handled by nav.generated).
      const candidates = sources.filter((f) => {
        const sz = ctx.size(f);
        return sz >= LARGE_LINES * 8 && sz <= HUGE_BYTES;
      });
      const counted = await ctx.mapFiles(
        candidates,
        (f, text) => {
          let n = 0;
          for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) === 10) n++;
          if (text.length > 0 && text[text.length - 1] !== '\n') n++;
          return n > LARGE_LINES && !GENERATED_HEADER.test(text.slice(0, 600)) ? { f, n } : null;
        },
        HUGE_BYTES,
      );
      const large = counted.filter((x): x is { f: string; n: number } => x !== null);
      large.sort((a, b) => b.n - a.n);
      if (sources.length === 0) return { score: null, summary: 'No source files' };
      const frac = large.length / sources.length;
      const score =
        // The share of oversized files drives the score; the per-file term is capped so a big repo
        // with a small share of large files isn't zeroed by absolute count alone.
        large.length === 0
          ? 1
          : Math.max(0, Math.min(0.9, 1 - frac * 10 - Math.min(0.3, 0.02 * large.length)));
      return {
        score,
        summary:
          large.length === 0
            ? `All ${sources.length} source files under ${LARGE_LINES} lines`
            : `${large.length} of ${sources.length} source files exceed ${LARGE_LINES} lines`,
        findings: large
          .slice(0, 10)
          .map(({ f, n }) => ({ severity: 'warn', file: f, message: `${n} lines` })),
        suggestion: large.length
          ? 'Split big files into focused modules — agents read whole files and lose the thread in giant ones.'
          : undefined,
      };
    },
  },
  {
    id: 'nav.generated',
    category: 'navigability',
    title: 'Generated/minified blobs hidden from agents',
    weight: 2,
    run(ctx): CheckResult {
      const findings: Finding[] = [];
      for (const f of ctx.files) {
        const base = f.slice(f.lastIndexOf('/') + 1);
        if (LOCKFILES.includes(base) || PY_LOCKS.includes(base) || f.endsWith('.snap')) continue;
        const sz = ctx.size(f);
        const vendored = isVendored(f) && SOURCE_EXT.test(f) && sz > 50 * 1024;
        const generatedName = (isGeneratedName(f) && sz > 50 * 1024) || vendored;
        const huge = sz > HUGE_BYTES && SOURCE_EXT.test(f);
        const bigText =
          sz > HUGE_BYTES && /\.(json|csv|tsv|txt|xml|svg|sql|log|ndjson|jsonl)$/.test(f);
        if (generatedName || huge || bigText) {
          findings.push({
            severity: 'warn',
            file: f,
            message: `${(sz / 1024).toFixed(0)} KB ${vendored ? 'vendored third-party code' : generatedName ? 'generated/minified' : 'blob'}`,
          });
        }
      }
      const lockfiles = ctx.files.filter((f) => LOCKFILES.includes(f));
      if (lockfiles.length > 1) {
        findings.push({
          severity: 'warn',
          message: `Multiple JS lockfiles (${lockfiles.join(', ')}) — agents may pick the wrong package manager`,
        });
      }
      const score = Math.max(0, 1 - 0.15 * findings.length);
      return {
        score,
        summary:
          findings.length === 0
            ? 'No large generated blobs in agent view'
            : `${findings.length} noisy file(s) visible to agents`,
        findings: findings.slice(0, 10),
        suggestion: findings.length
          ? 'Ignore build output in .gitignore; for committed generated files add them to `.ignore` (ripgrep) and `.cursorignore`.'
          : undefined,
      };
    },
  },
  {
    id: 'nav.depth',
    category: 'navigability',
    title: 'Shallow, navigable directory tree',
    weight: 1,
    run(ctx): CheckResult {
      const depths = ctx.files
        .filter((f) => SOURCE_EXT.test(f))
        .map((f) => f.split('/').length - 1);
      if (depths.length === 0) return { score: null, summary: 'No source files' };
      depths.sort((a, b) => a - b);
      const p95 = depths[Math.floor(depths.length * 0.95)] ?? 0;
      const max = depths[depths.length - 1] ?? 0;
      const score = p95 <= 6 ? 1 : p95 <= 8 ? 0.8 : p95 <= 10 ? 0.5 : 0.2;
      return {
        score,
        summary: `95% of source files within ${p95} levels (max ${max})`,
        suggestion:
          score < 1
            ? 'Flatten deeply nested directories; deep trees cost agents extra exploration steps.'
            : undefined,
      };
    },
  },
  {
    id: 'nav.readme',
    category: 'navigability',
    title: 'README exists',
    weight: 1,
    run(ctx): CheckResult {
      const readme = ctx.files.find((f) => /^readme(\.\w+)?$/i.test(f));
      if (!readme)
        return {
          score: 0,
          summary: 'No README',
          suggestion: 'Add a README describing what the project does and how to run it.',
        };
      const lines = ctx.lineCount(readme);
      return lines >= 10
        ? { score: 1, summary: `${readme} (${lines} lines)` }
        : {
            score: 0.5,
            summary: `${readme} is only ${lines} lines`,
            suggestion: 'Flesh out the README: purpose, setup, usage.',
          };
    },
  },
];
